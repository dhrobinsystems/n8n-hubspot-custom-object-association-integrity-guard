function nodeId(name) {
  const hex = createHash('sha256').update(`${WORKFLOW_NAME}:${name}`).digest('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function codeNode(name, position, modules, logic, notes) {
  return {
    parameters: { mode: 'runOnceForAllItems', jsCode: embed(modules, logic) },
    id: nodeId(name),
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position,
    notes,
    notesInFlow: false,
  };
}

function ifNode(name, position, leftValue, rightValue) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
        conditions: [{ id: nodeId(`${name}:condition`), leftValue, rightValue, operator: { type: 'string', operation: 'equals' } }],
        combinator: 'and',
      },
      options: {},
    },
    id: nodeId(name),
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2,
    position,
  };
}

const HUBSPOT_AUTH = { parameters: [{ name: 'Authorization', value: '=Bearer {{ $env.HUBSPOT_PRIVATE_APP_TOKEN }}' }] };
const RETRY = { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 };

function hubspotNode(name, position, method, extraOptions = {}, notes = '') {
  const parameters = {
    method,
    url: '={{ $json.request.url }}',
    sendHeaders: true,
    headerParameters: HUBSPOT_AUTH,
    options: { timeout: 30000, ...extraOptions },
  };
  if (method === 'POST') {
    parameters.sendBody = true;
    parameters.specifyBody = 'json';
    parameters.jsonBody = '={{ JSON.stringify($json.request.body) }}';
  }
  return { parameters, id: nodeId(name), name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position, ...RETRY, notes, notesInFlow: false };
}

function slackNode(name, position) {
  return {
    parameters: {
      method: 'POST',
      url: "={{ $json.slackTarget === 'production' ? $env.SLACK_WEBHOOK_URL : $env.SLACK_SANDBOX_WEBHOOK_URL }}",
      sendBody: true,
      specifyBody: 'json',
      jsonBody: '={{ JSON.stringify($json.message) }}',
      options: { timeout: 15000 },
    },
    id: nodeId(name),
    name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position,
    retryOnFail: true,
    maxTries: 2,
    waitBetweenTries: 2000,
    notes: 'The webhook URL is read from $env at request time, so it never appears in item data.',
    notesInFlow: false,
  };
}

